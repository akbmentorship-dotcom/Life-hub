const assert=require('node:assert/strict');
const F=require('../budget-engine.js');
const debt={id:'loan',name:'Test loan',opening:100000,asOf:'2026-01-01',apr:36.5,payment:20000,frequency:'monthly',nextDue:'2026-02-01'};
let s={...F.empty(),debts:[debt],schedule:{anchor:'2026-01-02',days:14}};
assert.equal(F.balance(debt,[],'2026-01-11').amount,101000);
s=F.payment(s,'loan',10000,'2026-01-11','p1');
assert.equal(F.balance(debt,s.events,'2026-01-21').amount,91910);
assert.equal(F.payment(s,'loan',10000,'2026-01-11','p1').events.length,1);
assert.throws(()=>F.payment(s,'loan',999999,'2026-01-11','p2'),/exceeds/);
s.events.push({id:'r1',debtId:'loan',type:'reconcile',amount:80000,date:'2026-01-15'});
assert.equal(F.balance(debt,s.events,'2026-01-25').amount,80800);
assert.equal(F.balance(debt,s.events,'2026-01-25').confirmed.amount,80000);
assert.equal(F.next('2026-01-31','monthly'),'2026-02-28');
assert.deepEqual(F.occurrences({...debt,nextDue:'2026-01-31'},'2026-01-01','2026-04-01'),['2026-01-31','2026-02-28','2026-03-31']);
assert.equal(F.nextPayday(s.schedule,'2026-01-03'),'2026-01-16');
assert.equal(F.nextPayday(s.schedule,'2026-01-16',false),'2026-01-30');
assert.equal(F.nextPayday({anchor:'2024-02-29',days:14},'2024-03-01'),'2024-03-14');
const noInterest={...debt,apr:0,nextDue:'2026-01-01'};
assert.equal(F.forecast(noInterest,[],'2026-01-01').date,'2026-05-01');
assert.equal(F.forecast({...debt,payment:0},[],'2026-01-01').date,null);
assert.equal(F.forecast({...debt,opening:0},[],'2026-01-01').date,'2026-01-01');
const map={name:0,balance:1,apr:2,payment:3,frequency:4,nextDue:5};
let rows=F.importRows([['Visa',900,'19.99%',50,'monthly','2026-01-20'],['Other',500,'0',100,'biweekly','2026-01-16']],map,'debt','2026-01-01');
assert.equal(rows[0].opening,0);assert.equal(rows[1].opening,50000);
assert.equal(F.importRows([['A',1,0.1999,1]],{...map,fractionRate:true},'debt','2026-01-01')[0].apr,19.99);
assert.throws(()=>F.importRows([['A',1,0,1],[' a ',1,0,1]],map,'debt','2026-01-01'),/Duplicate/);
assert.throws(()=>F.importRows([['A','',0,1]],map,'debt','2026-01-01'));
assert.throws(()=>F.importRows([['A',1,'bad',1]],map,'debt','2026-01-01'));
let merged=F.merge(s,[{...debt,opening:900000,apr:10}],'debt','hash');
assert.equal(merged.debts[0].opening,100000);assert.equal(merged.events.length,2);assert.equal(merged.debts[0].apr,10);
assert.throws(()=>F.merge(merged,rows,'debt','hash'),/already/);
const allocState={...F.empty(),schedule:{anchor:'2026-01-01',days:14},debts:[{...noInterest,nextDue:'2026-01-10'}],bills:[{id:'rent',name:'Rent',amount:50000,frequency:'monthly',nextDue:'2026-01-05'}]};
let plan=F.allocation(allocState,100000,'2026-01-01');assert.equal(plan.rows[0].allocated,50000);assert.equal(plan.rows[1].allocated,20000);assert.equal(plan.rows[2].allocated,30000);assert.equal(plan.left,0);
plan=F.allocation(allocState,10000,'2026-01-01');assert.equal(plan.shortfall,60000);
assert.deepEqual(F.validate(JSON.parse(JSON.stringify(s))),s);
assert.throws(()=>F.validate({...s,events:[{id:'x',debtId:'missing',type:'payment',amount:1,date:'2026-01-01'}]}));
assert.throws(()=>F.date('2026-02-30'));
assert.equal(F.money('0'),0);assert.equal(F.money('$1,234.56'),123456);assert.throws(()=>F.money(''));
const rateDebt={...debt,initialApr:36.5,apr:0,rates:[{date:'2026-01-11',apr:0}]};
assert.equal(F.balance(rateDebt,[],'2026-01-21').amount,101000,'Rate changes do not rewrite earlier accrual');
const split={...noInterest,payment:20000,installments:[{amount:10000,frequency:'monthly',nextDue:'2026-01-01'},{amount:10000,frequency:'monthly',nextDue:'2026-01-16'}]};
assert.deepEqual(F.duePayments(split,'2026-01-01','2026-02-01').map(d=>d.date),['2026-01-01','2026-01-16']);
assert.equal(F.forecast(split,[],'2026-01-01').date,'2026-05-16');
assert.equal(F.nextPayday({anchor:'2026-01-01',days:14,mode:'semimonthly'},'2026-02-16',false),'2026-03-01');
const cascade={...allocState,bills:[],debts:[{...noInterest,opening:10000,payment:0},{...noInterest,id:'second',name:'Second',opening:20000,payment:0}]};
assert.equal(F.allocation(cascade,40000,'2026-01-01').left,10000,'Extra cascades through all debts');
assert.equal(F.allocation({...cascade,strategy:'snowball'},40000,'2026-01-01').rows[0].id,'loan');
console.log('PASS: payments, interest, reconciliation, calendar/payday scheduling, imports, deduplication, allocation, payoff forecasts, backup validation');
