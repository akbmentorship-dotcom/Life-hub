const assert=require('node:assert/strict');
const F=require('../budget-engine.js'),S=require('../budget-scenarios.js');
const on='2026-01-01';
const debt={id:'loan',name:'Test loan',opening:100000,asOf:on,apr:0,payment:10000,frequency:'monthly',nextDue:on};
const state={...F.empty(),debts:[debt]};
const input={monthlySurplus:0,debtShare:100,newDebtShare:100,incomeDelta:10000,spendingDelta:0,oneOffDebt:0,oneOffSavings:0,oneOffCost:0,goalName:'',goalTarget:0,goalSaved:0,goalDeadline:'',newStrategy:'avalanche',startDate:on};
const before=JSON.stringify(state);
let r=S.compare(state,input,on);
assert.equal(r.baseline.debtFreeDate,'2026-10-01');assert.equal(r.scenario.debtFreeDate,'2026-05-01');
assert.equal(JSON.stringify(state),before,'Scenario calculations do not mutate real Finance data');
assert.equal(S.compare(state,{...input,incomeDelta:0,spendingDelta:-10000},on).scenario.debtFreeDate,'2026-05-01');
assert.equal(S.compare(state,{...input,incomeDelta:0,oneOffDebt:100000},on).scenario.debtFreeDate,on);
assert.equal(S.compare(state,{...input,startDate:'2026-04-01'},on).scenario.debtFreeDate,'2026-07-01');
r=S.compare({...state,debts:[]},{...input,monthlySurplus:10000,debtShare:0,newDebtShare:0,goalTarget:100000,goalName:'Goal'},on);
assert.equal(r.baseline.savingsDate,'2026-10-01');assert.equal(r.scenario.savingsDate,'2026-05-01');
r=S.compare(state,{...input,monthlySurplus:10000,incomeDelta:0,newDebtShare:0,goalTarget:30000,goalName:'Goal'},on);
assert.ok(r.scenario.savingsDate<r.baseline.savingsDate,'Prioritizing savings brings its goal forward');
assert.ok(r.scenario.debtFreeDate>r.baseline.debtFreeDate,'Tradeoff delays debt payoff');
r=S.compare(state,{...input,monthlySurplus:10000,incomeDelta:-20000},on);
assert.equal(r.scenario.shortfall,10000);assert.equal(r.scenario.debtFreeDate,null);assert.equal(r.scenario.interest,null);
const interestDebt={...debt,apr:36.5,nextDue:'2026-02-01',payment:20000};
assert.equal(S.compare({...state,debts:[interestDebt]},{...input,incomeDelta:0},on).baseline.debtFreeDate,F.forecast(interestDebt,[],on).date);
const rollover={...state,debts:[{...debt,id:'small',opening:20000},debt]};
assert.equal(S.compare(rollover,{...input,incomeDelta:0},on).baseline.debtFreeDate,'2026-06-01');
r=S.compare({...state,debts:[{...debt,payment:0}]},{...input,incomeDelta:0},on);
assert.equal(r.baseline.debtFreeDate,null);assert.equal(r.baseline.interestComplete,false);
r=S.compare({...state,debts:[]},{...input,monthlySurplus:0,incomeDelta:0,goalTarget:10000,goalSaved:10000},on);
assert.equal(r.baseline.savingsDate,on);
const saved={...state,whatIf:[{id:'scenario',name:'Test scenario',input}]};
assert.deepEqual(F.validate(JSON.parse(JSON.stringify(saved))),saved);
assert.throws(()=>F.validate({...saved,whatIf:[{...saved.whatIf[0],input:{...input,incomeDelta:NaN}}]}),/scenario/);
assert.throws(()=>S.compare(state,{...input,newDebtShare:101},on),/scenario/);
assert.throws(()=>S.compare(state,{...input,startDate:'2025-12-01'},on),/future/);
assert.deepEqual(S.compare(state,{...input,incomeDelta:0,newStrategy:state.strategy},on).baseline,S.compare(state,{...input,incomeDelta:0,newStrategy:state.strategy},on).scenario,'No decisions produce identical forecasts');
console.log('PASS: debt/savings dates, cashflow changes, shortfalls, future decisions, interest, rollover, unreachable goals, immutability, saved-scenario backup validation');

r=S.compare({...state,debts:[]},{...input,monthlySurplus:10000,incomeDelta:0,debtShare:0,newDebtShare:0,goalTarget:50000,goalSaved:10000,oneOffCost:10000},on);
assert.equal(r.baseline.savingsDate,'2026-04-01');assert.equal(r.scenario.savingsDate,'2026-05-01');
r=S.compare({...state,debts:[]},{...input,incomeDelta:0,goalTarget:50000,goalSaved:10000,oneOffCost:20000},on);
assert.equal(r.scenario.shortfall,10000);assert.equal(r.scenario.shortfallPeriod,'one-time');
console.log('PASS: one-time purchases delay savings goals; unfunded withdrawals are flagged');
